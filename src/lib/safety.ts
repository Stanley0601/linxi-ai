/**
 * 安全模块：危机信号检测 + 干预响应
 *
 * 灵犀的目标场景明确包含"心情低落想倾诉"。当用户表露自伤/自杀倾向时，
 * 陪伴产品有责任接住：角色不回避、不敷衍，同时把专业求助渠道递到用户手边。
 *
 * 设计原则：宁可误报（多一句关心），不可漏报。
 */

/** 高风险信号：自杀/自伤意念 */
const CRISIS_PATTERNS: RegExp[] = [
  /不想活/,
  /想死|去死|死了算了|死了更好/,
  /自杀|轻生/,
  /自残|割腕|安眠药/,
  /活着(真|太)?(没意思|没意义|好累|没劲)/,
  /没有?人(会)?在乎我|没人需要我/,
  /结束(自己的)?生命/,
  /从(楼上|桥上)跳|跳楼/,
  /撑不下去|熬不下去|坚持不下去了/,
];

export function detectCrisisSignal(text: string): boolean {
  const t = text.trim();
  if (!t) return false;
  return CRISIS_PATTERNS.some(p => p.test(t));
}

/** 危机模式下注入 system prompt 的指令（覆盖常规聊天规则） */
export function buildCrisisPromptBlock(): string {
  return `## 重要：对方可能正处于情绪危机中
对方刚才的话透露出可能的自伤或轻生念头。此刻最重要的事：
1. 认真对待，绝不轻描淡写、开玩笑或转移话题。
2. 先表达你真的在、你在乎："我在呢"、"跟我说说好吗"。
3. 倾听而不是说教。不要讲大道理，不要说"想开点"。
4. 温柔而明确地鼓励对方寻求专业帮助，告诉对方打心理援助热线不丢人，你会陪着。
5. 这一条消息可以比平时长一点、认真一点，暂时不用管字数和分条限制。`;
}

